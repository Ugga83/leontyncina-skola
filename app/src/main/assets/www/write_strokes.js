// diacritics: base letter + mark ('a' acute, 'h' háček, 'z' zobáček, 'r' kroužek)
const ACC = {'á':['a','a'],'é':['e','a'],'í':['i','a'],'ó':['o','a'],'ú':['u','a'],'ý':['y','a'],'ů':['u','r'],
  'č':['c','h'],'ď':['d','z'],'ě':['e','h'],'ň':['n','h'],'ř':['r','h'],'š':['s','h'],'ť':['t','z'],'ž':['z','h'],
  'Á':['A','a'],'É':['E','a'],'Í':['I','a'],'Ó':['O','a'],'Ú':['U','a'],'Ý':['Y','a'],'Ů':['U','r'],
  'Č':['C','h'],'Ď':['D','h'],'Ě':['E','h'],'Ň':['N','h'],'Ř':['R','h'],'Š':['S','h'],'Ť':['T','h'],'Ž':['Z','h']};
const base = ch => ACC[ch] ? ACC[ch][0] : ch;
// the mark above a letter (x = middle of the letter, top = top of the letter)
function mark(kind, x, top, stemX){
  const y = top - .32;
  if (kind==='a') return acute(x, y);
  if (kind==='h') return hacek(x, y);
  if (kind==='r') return ring(x, y);
  return hook(stemX + .22, top);                                        // zobáček vpravo vedle horního konce dříku
}
// does the alphabet know every letter of x?
function knows(x, print){ return [...x].every(ch=>{ const b = base(ch); return print ? PR[b] : (CUR[b] || CAP[b]); }); }
const shift = (pts, dx) => pts.map(p=>[p[0] + dx, p[1]]);
const tall = b => /[A-Zbdfhklt]/.test(b);

// ---------- one word: strokes in units ----------
function build(x, print){
  if (!knows(x, print)) return null;
  const strokes = [], later = [];
  let cx = 0;
  if (print){
    [...x].forEach(ch=>{
      const b = base(ch), g = PR[b];
      g.st.forEach(s=>strokes.push(shift(s, cx)));
      if (ACC[ch]){ const top = tall(b) ? -2 : -1; strokes.push(mark(ACC[ch][1], cx + g.w / 2, top - .12, cx + g.w)); }
      cx += g.w + .35;                                                  // mezera mezi písmeny
    });
    return {strokes, w: cx - .35};
  }
  let cur = null, exit = null;                                          // the stroke being written without lifting
  const flush = () => { if (cur && cur.length > 1) strokes.push(cur); cur = null; };
  [...x].forEach(ch=>{
    const b = base(ch), big = CAP[b], g = big || CUR[b];
    let main = shift(g.main, cx);
    if (cur && exit){
      if (!big && g.s === 'up'){
        // the upstroke starts where the previous letter ended: skip its part below the exit height
        const k = main.findIndex(p=>p[1] <= exit[1]);
        main = [exit].concat(main.slice(Math.max(1, k)));
      } else {
        // to an oval letter (up to 2 h, back CCW) or an arch: straight from the exit to the start
        main = J(L(exit, main[0], 8), main);
      }
      cur = cur.concat(main.slice(1));
    } else { flush(); cur = main.slice(); }
    (g.extra || []).forEach(e=>{ flush(); cur = shift(e, cx); });       // a capital with a second stroke: lift, then on
    if (!(ACC[ch] && b==='i')) (g.after || []).forEach(a=>later.push(shift(a, cx)));
    if (ACC[ch]){
      const top = big ? -2 : tall(b) ? -1.7 : -1, mid = cx + (b==='i' || b==='j' ? .42 : g.w * .5);
      later.push(ACC[ch][1]==='z' ? mark('z', mid, b==='t' ? -1.66 : -2, cx + (b==='t' ? .5 : .71)) : mark(ACC[ch][1], mid, top, 0));
    }
    // a capital that does not join: lift the pen, the next letter starts close beside it
    if (big && !big.nap){ exit = null; flush(); cx += g.w + .12; return; }
    exit = cur[cur.length - 1];
    cx += g.w;
  });
  flush();
  // dots, crossbars and accents come after the whole word
  return {strokes: strokes.concat(later), w: cx};
}
window.WSTROKES = {build, knows, CUR, CAP, PR};
