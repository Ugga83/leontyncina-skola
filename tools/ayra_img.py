#!/usr/bin/env python3
"""Packs Ayra's pictures into www/ayra_img.js as data URLs, so the animation (ayra.js, WebGL) may use them
even when the app is opened from file:// (images from files would be blocked for WebGL).
Run after changing ayra_full.png, ayra_walk.png or ayra_sleep.png:  python3 tools/ayra_img.py"""
import base64, os
WWW = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'assets', 'www')
out = []
for k in ('full', 'walk', 'sleep'):
    with open(os.path.join(WWW, f'ayra_{k}.png'), 'rb') as f:
        out.append(f"  {k}:'data:image/png;base64,{base64.b64encode(f.read()).decode()}'")
with open(os.path.join(WWW, 'ayra_img.js'), 'w') as f:
    f.write('// generated by tools/ayra_img.py – Ayra\'s pictures for the animation (ayra.js)\nwindow.AYRA_IMG = {\n' + ',\n'.join(out) + '\n};\n')
print('ok')
